export const getToolTitle = (tool: ToolDefinition, locale: Locale) =>
  locale === 'zh-CN' ? (chineseToolTitles[tool.slug] ?? tool.title.en) : tool.title[locale]

export const getToolDescription = (tool: ToolDefinition, locale: Locale) => {
  if (locale === 'zh-CN') return chineseToolDescriptions[tool.slug] ?? tool.description.en
  return tool.description[locale]
}

