const chineseCopyByEnglish = new Map(
  [
    ...chineseCopy,
    ...toolGuideFirstHalfChineseCopy,
    ...toolGuideChineseCopy,
    ...unitAndCronChineseCopy,
    ...kaomojiChineseCopy,
    ...workspaceChineseCopy,
    ...sourceDataChineseCopy,
  ].map(([source, translated]) => [source.toLowerCase(), translated]),
)
const dynamicChineseTranslations: [RegExp, (match: RegExpMatchArray) => string][] = [
  [/^quality \((.+)\)$/, ([, value]) => `质量（${value}）`],
  [/^convert (\d+) file\(s\)$/, ([, count]) => `转换 ${count} 个文件`],
  [/^compress (\d+) file\(s\)$/, ([, count]) => `压缩 ${count} 个文件`],
  [/^done in (.+)ms$/, ([, time]) => `用时 ${time} 毫秒`],
  [/^size \((.+)px\)$/, ([, size]) => `粗细（${size} 像素）`],
  [/^tolerance \((.+)\)$/, ([, value]) => `容差（${value}）`],
  [/^(.+) passed$/, ([, count]) => `通过 ${count} 项`],
  [/^(.+) warnings?$/, ([, count]) => `${count} 项警告`],
  [/^(.+) failed$/, ([, count]) => `${count} 项失败`],
  [/^first (\d+) rows$/, ([, count]) => `前 ${count} 行`],
  [/^(\d+)-bit$/, ([, bits]) => `${bits} 位`],
  [/^ln (\d+), col (\d+)$/, ([, line, column]) => `第 ${line} 行，第 ${column} 列`],
  [/^matches \((\d+)\)$/, ([, count]) => `匹配结果（${count}）`],
  [/^laps \((\d+)\)$/, ([, count]) => `圈数（${count}）`],
  [/^([+-]?\d+) day$/, ([, days]) => `${days} 天`],
  [/^(.+)d left$/, ([, days]) => `剩余 ${days} 天`],
  [/^(\d+) min$/, ([, minutes]) => `${minutes} 分钟`],
  [/^(\d+)s$/, ([, seconds]) => `${seconds} 秒`],
]

export const getChineseCopy = (englishCopy: string) => {
  const normalized = englishCopy.toLowerCase()
  for (const [pattern, translate] of dynamicChineseTranslations) {
    const match = normalized.match(pattern)
    if (match) return translate(match)
  }
  return chineseCopyByEnglish.get(normalized)
}

/**
 * Picks the copy for the active locale. Keeps bilingual literals next to the
 * markup that renders them, which reads better than a dictionary entry for
 * strings that only ever appear in one place.
 */
export const useTranslate = () => {
  const { locale } = useLocale()
  return (ja: string, en: string, zh?: string) => {
    if (locale === 'ja') {
      return ja
    }
    if (locale === 'zh-CN') {
      return zh ?? getChineseCopy(en) ?? en
    }
    return en
  }
}
